"""Rebuild the embedded CUDA module (score_ptx.hpp) from score.cu.

usage: python3 gen_ptx.py <libnvrtc.so.12 or nvrtc64_120_0.dll> [ptxas]

NVRTC 12.9 compiles score.cu to compute_75 PTX. When ptxas is supplied, the PTX
is also assembled to SASS cubins for sm_75, sm_80, sm_86 and sm_89 (RTX 4060 Ti,
Ada Lovelace). At run time the host loads the cubin with the same major and the
highest minor not above the device's compute capability, which needs only a
CUDA 12 driver (minor-version compatibility). Other devices JIT-compile the PTX,
which needs a driver that supports the PTX ISA version (CUDA 12.9 or newer).
"""
import ctypes as c
from pathlib import Path
import hashlib
import subprocess
import sys
import tempfile

here = Path(__file__).resolve().parent
lib = c.CDLL(sys.argv[1])
ptxas = sys.argv[2] if len(sys.argv) > 2 else None
ARCHES = ['sm_75', 'sm_80', 'sm_86', 'sm_89']


def check(rc, program=None):
    if rc:
        if program is not None:
            size = c.c_size_t()
            lib.nvrtcGetProgramLogSize(program, c.byref(size))
            log = c.create_string_buffer(size.value)
            lib.nvrtcGetProgramLog(program, log)
            sys.stderr.write(log.value.decode(errors='replace'))
        raise RuntimeError(f'NVRTC error {rc}')


source = (here / 'score.cu').read_bytes().replace(b'\r\n', b'\n')
program = c.c_void_p()
check(lib.nvrtcCreateProgram(c.byref(program), source, b'score.cu', 0, None, None))
options = (c.c_char_p * 1)(b'--gpu-architecture=compute_75')
check(lib.nvrtcCompileProgram(program, 1, options), program)
size = c.c_size_t()
check(lib.nvrtcGetPTXSize(program, c.byref(size)))
ptx = c.create_string_buffer(size.value)
check(lib.nvrtcGetPTX(program, ptx))
check(lib.nvrtcDestroyProgram(c.byref(program)))

out = [b'// score.cu SHA256 ' + hashlib.sha256(source).hexdigest().encode(),
       b'// Generated by gen_ptx.py (NVRTC 12.9, compute_75 PTX' + (b' + SASS ' + ' '.join(ARCHES).encode() if ptxas else b'') + b')',
       b'#pragma once',
       b'static constexpr char scorePTX[]=R"ptx(' + ptx.value + b')ptx";']
cubins = []
if ptxas:
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / 'score.ptx'
        src.write_bytes(ptx.value)
        for arch in ARCHES:
            dst = Path(tmp) / (arch + '.cubin')
            subprocess.run([ptxas, '-arch=' + arch, str(src), '-o', str(dst)], check=True)
            data = dst.read_bytes()
            name = 'scoreCubin_' + arch
            body = b','.join(str(x).encode() for x in data)
            out.append(b'alignas(8) static const unsigned char ' + name.encode() + b'[]={' + body + b'};')
            cubins.append((arch, name, len(data), hashlib.sha256(data).hexdigest()))
out.append(b'struct ScoreCubin { int major, minor; const unsigned char *data; unsigned long size; const char *sha256; };')
out.append(b'static const ScoreCubin scoreCubins[]={' + b','.join(
    f'{{{a[3]},{a[4]},{n},{s}UL,"{h}"}}'.encode() for a, n, s, h in cubins) + (b'' if cubins else b'{0,0,nullptr,0,""}') + b'};')
out.append(b'static constexpr int scoreCubinCount=' + str(len(cubins)).encode() + b';')
(here / 'score_ptx.hpp').write_bytes(b'\n'.join(out) + b'\n')
print('PTX', len(ptx.value), 'bytes;', ', '.join(f'{a} {s} bytes' for a, _, s, _ in cubins))
