"""EightMax 3.8: interleaved native timing of two mwcli builds on identical specs.
usage: python3 native-timing.py <specs-dir> <mwcli-A> <mwcli-B> <out.json> [reps] [threads...]
specs-dir holds one sub-directory per scenario with <seed>.json specs (generated by
validation/3.7/scenarios.js with EM_SPEC_DIR). Runs alternate A/B per repetition
so drift affects both; each run also checks that both exported states are byte-identical."""
import json,subprocess,sys,pathlib,statistics,random,tempfile,hashlib,math
specs=pathlib.Path(sys.argv[1]);A,B=sys.argv[2],sys.argv[3];out=pathlib.Path(sys.argv[4])
reps=int(sys.argv[5]) if len(sys.argv)>5 else 15;threads=sys.argv[6:] or ['1','4']
tmp=pathlib.Path(tempfile.mkdtemp())
def run(cli,spec,u,t):
    st=tmp/'s.state';r=subprocess.run([cli,str(spec),u,t,str(st),'2048'],capture_output=True,text=True,check=True)
    info=json.loads(r.stdout);return info['wallSeconds']*1000,info['processPeakRssMiB'],hashlib.sha256(st.read_bytes()).hexdigest(),info.get('stateVisits')
res={'reps':reps,'A':A,'B':B,'scenarios':[]}
for d in sorted(p for p in specs.iterdir() if p.is_dir()):
    u='20000' if d.name.startswith(('Heads','Three')) else '80'
    import os; u=os.environ.get('EM_UPDATES_'+('LONG' if u=='20000' else 'SHORT'),u)
    for t in threads:
        a=[];b=[];same=True;ra=[];rb=[]
        for i in range(reps):
            spec=d/f'{i%3+1}.json'
            order=[(A,a,ra),(B,b,rb)] if i%2==0 else [(B,b,rb),(A,a,ra)]
            hs=[]
            for cli,acc,rss in order:
                ms,mib,h,v=run(cli,spec,u,t);acc.append(ms);rss.append(mib);hs.append(h)
            same&=hs[0]==hs[1]
        ratio=[x/y for x,y in zip(b,a)];lr=[math.log(r) for r in ratio];m=statistics.mean(lr);se=statistics.stdev(lr)/math.sqrt(len(lr))
        row={'scenario':d.name,'updates':int(u),'threads':int(t),'medianMsA':statistics.median(a),'medianMsB':statistics.median(b),
             'geomeanRatioB_over_A':math.exp(m),'ratio95':[math.exp(m-2.0*se),math.exp(m+2.0*se)],'peakRssMiBA':max(ra),'peakRssMiBB':max(rb),'identicalStates':same,'msA':a,'msB':b}
        res['scenarios'].append(row);print(f"{d.name:28s} t={t} A {row['medianMsA']:7.2f} B {row['medianMsB']:7.2f} B/A {row['geomeanRatioB_over_A']:.3f} [{row['ratio95'][0]:.3f},{row['ratio95'][1]:.3f}] same={same}",flush=True)
        out.write_text(json.dumps(res,indent=1))
